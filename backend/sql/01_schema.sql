    ALTER TABLE EMPRESA ADD EMPCIF VARCHAR(20) NULL;
GO
IF NOT EXISTS (SELECT 1 FROM sys.columns WHERE object_id=OBJECT_ID('EMPRESA') AND name='EMPDIR')
    ALTER TABLE EMPRESA ADD EMPDIR VARCHAR(80) NULL;
GO
IF NOT EXISTS (SELECT 1 FROM sys.columns WHERE object_id=OBJECT_ID('EMPRESA') AND name='EMPPOB')
    ALTER TABLE EMPRESA ADD EMPPOB VARCHAR(50) NULL;
GO
IF NOT EXISTS (SELECT 1 FROM sys.columns WHERE object_id=OBJECT_ID('EMPRESA') AND name='EMPTEL')
    ALTER TABLE EMPRESA ADD EMPTEL VARCHAR(20) NULL;
GO
IF NOT EXISTS (SELECT 1 FROM sys.columns WHERE object_id=OBJECT_ID('EMPRESA') AND name='EMPEML')
    ALTER TABLE EMPRESA ADD EMPEML VARCHAR(80) NULL;
GO

