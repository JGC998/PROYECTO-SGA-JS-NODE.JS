-- ── ALBARANCS (movimientos) ───────────────────────────────────
IF NOT EXISTS (SELECT 1 FROM sys.objects WHERE name='ALBARANCS' AND type='U')
CREATE TABLE ALBARANCS (
    ACSEMPCOD  VARCHAR(10)  NOT NULL DEFAULT '',
    ACSSER     VARCHAR(10)  NOT NULL,
    ACSNUM     INT          NOT NULL,
    ACSMOV     VARCHAR(4)   NOT NULL,
    ACSFEC     DATETIME     NOT NULL DEFAULT GETDATE(),
    ACSHOR     DATETIME     NULL,
    ACSARTCOD  VARCHAR(30)  NOT NULL,
    ACSUBI     VARCHAR(20)  NOT NULL DEFAULT '',
    ACSLOT     VARCHAR(30)  NULL,
    ACSCAN     FLOAT        NOT NULL DEFAULT 0,
    ACSCLICOD  VARCHAR(20)  NOT NULL DEFAULT '',
    ACSCLINOM  VARCHAR(80)  NULL,
    ACSNUMPIC  INT          NULL,
    ACSREPCOD  VARCHAR(20)  NULL,
    ACSNUMCAJ  INT          NULL,
    ACSNUMPAL  INT          NULL,
    ACSCENCOD  VARCHAR(10)  NULL
);
GO

CREATE INDEX IX_ALBARANCS_MOV  ON ALBARANCS (ACSMOV, ACSFEC);
CREATE INDEX IX_ALBARANCS_ART  ON ALBARANCS (ACSARTCOD, ACSFEC);
CREATE INDEX IX_ALBARANCS_NUM  ON ALBARANCS (ACSNUM, ACSSER);
GO

