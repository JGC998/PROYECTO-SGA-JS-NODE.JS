    EMPDIR     VARCHAR(80) NULL,
    EMPPOB     VARCHAR(50) NULL,
    EMPTEL     VARCHAR(20) NULL,
    EMPEML     VARCHAR(80) NULL
);
GO
-- Columnas añadidas en v2 — seguras de ejecutar sobre tabla existente
