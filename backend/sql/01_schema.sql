-- ── EMPRESA ──────────────────────────────────────────────────
IF NOT EXISTS (SELECT 1 FROM sys.objects WHERE name='EMPRESA' AND type='U')
CREATE TABLE EMPRESA (
    EMPCOD     VARCHAR(10) NOT NULL PRIMARY KEY,
    EMPNOM     VARCHAR(80) NOT NULL,
    EMPALMCOD  VARCHAR(10) NOT NULL DEFAULT '',
    EMPTIPEMP  INT         NOT NULL DEFAULT 0,
